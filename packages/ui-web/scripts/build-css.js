// @ts-check
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cssVariables } from '@vouch/ui-tokens';

/**
 * `styles.css` = the token variables + the component styles. A static file the apps import,
 * so no inline CSS is needed (a strict Content-Security-Policy stays possible).
 * @param {string} root  The package directory.
 */
export const paths = (root) => ({
  styles: join(root, 'styles.css'),
  components: join(root, 'src', 'components.css'),
});

/** @param {string} root */
export async function buildCss(root) {
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- a fixed file in this package
  const components = await readFile(paths(root).components, 'utf8');
  return `/* Generated by packages/ui-web/scripts/build-css.js. Do not edit. */\n${cssVariables()}\n\n${components}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- a fixed file in this package
  await writeFile(paths(root).styles, await buildCss(root));
  process.stdout.write(`wrote ${paths(root).styles}\n`);
}
